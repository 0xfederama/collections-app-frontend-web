// Turns the vendored OpenAPI spec into the files under src/generated/.
// Shared by api-sync.mjs (writes them) and api-check.mjs (compares them), so both always agree.
import { createHash } from 'node:crypto'
import openapiTS, { astToString } from 'openapi-typescript'
import yaml from 'js-yaml'

const METHODS = ['get', 'put', 'post', 'patch', 'delete']

export const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex')

// Follows local `#/…` references only (the spec has no external ones).
function deref(spec, node) {
  let current = node
  while (current && typeof current === 'object' && typeof current.$ref === 'string') {
    if (!current.$ref.startsWith('#/')) throw new Error(`unsupported $ref: ${current.$ref}`)
    current = current.$ref
      .slice(2)
      .split('/')
      .reduce((acc, key) => acc?.[key.replaceAll('~1', '/').replaceAll('~0', '~')], spec)
  }
  return current
}

// The first success response of every operation, with its first example (if any).
function extractExamples(spec) {
  const out = {}
  for (const [path, item] of Object.entries(spec.paths)) {
    for (const method of METHODS) {
      const op = item[method]
      if (!op) continue
      const code = Object.keys(op.responses)
        .filter((c) => /^2\d\d$/.test(c))
        .sort()[0]
      if (!code) throw new Error(`${op.operationId}: no 2xx response`)
      const response = deref(spec, op.responses[code])
      const contentTypes = Object.keys(response.content ?? {})
      const contentType = contentTypes.includes('application/json')
        ? 'application/json'
        : (contentTypes[0] ?? null)
      const media = contentType ? response.content[contentType] : undefined
      const first = media?.examples ? Object.values(media.examples)[0] : undefined
      const body = first ? deref(spec, first).value : media?.example
      out[op.operationId] = {
        method,
        path,
        status: Number(code),
        contentType,
        ...(body === undefined ? {} : { body }),
      }
    }
  }
  return out
}

// Returns { 'schema.d.ts': string, 'examples.ts': string }, ready to write byte for byte.
export async function generate(specBytes) {
  const spec = yaml.load(Buffer.from(specBytes).toString('utf8'))

  const schema = astToString(await openapiTS(spec))

  const examples = `// AUTO-GENERATED by scripts/api-sync.mjs from api/openapi.yaml. Do not edit; run \`npm run api:sync\`.
import type { operations } from './schema'

/** The first 2xx response of an operation and its first spec example (used by the MSW mocks). */
export interface ExampleResponse {
  method: 'get' | 'put' | 'post' | 'patch' | 'delete'
  /** OpenAPI path template, e.g. \`/api/v1/items/{id}\`. */
  path: string
  status: number
  contentType: string | null
  body?: unknown
}

export const exampleResponses: Record<keyof operations, ExampleResponse> = ${JSON.stringify(extractExamples(spec), null, 2)}
`
  return { 'schema.d.ts': schema, 'examples.ts': examples }
}
